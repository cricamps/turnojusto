-- ---------------------------------------------------------------------
-- REGION: Catálogo de las 16 regiones de Chile (código ISO 3166-2:CL)
-- ---------------------------------------------------------------------
CREATE TABLE REGION (
    REGION_CODIGO              VARCHAR2(5) NOT NULL,
    NOMBRE                     VARCHAR2(60) NOT NULL,
    ORDEN                      NUMBER(2) NOT NULL,
    CONSTRAINT PK_REGION PRIMARY KEY (REGION_CODIGO),
    CONSTRAINT UQ_REGION_NOMBRE UNIQUE (NOMBRE)
);
COMMENT ON TABLE REGION IS 'Catálogo de las 16 regiones de Chile (código ISO 3166-2:CL)';
COMMENT ON COLUMN REGION.REGION_CODIGO IS 'Código ISO, por ejemplo CL-RM';
COMMENT ON COLUMN REGION.NOMBRE IS 'Nombre oficial de la región';
COMMENT ON COLUMN REGION.ORDEN IS 'Orden geográfico de norte a sur';

-- ---------------------------------------------------------------------
-- EMPRESA: Cliente de la plataforma (tenant)
-- ---------------------------------------------------------------------
CREATE TABLE EMPRESA (
    EMPRESA_ID                 NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    RUT                        VARCHAR2(12) NOT NULL,
    RAZON_SOCIAL               VARCHAR2(150) NOT NULL,
    NOMBRE_FANTASIA            VARCHAR2(100),
    CORREO_CONTACTO            VARCHAR2(254) NOT NULL,
    TELEFONO                   VARCHAR2(20),
    ESTADO                     VARCHAR2(10) DEFAULT 'ACTIVA' NOT NULL,
    CREADO_EN                  TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CREADO_POR                 VARCHAR2(36) NOT NULL,
    ACTUALIZADO_EN             TIMESTAMP WITH TIME ZONE,
    ACTUALIZADO_POR            VARCHAR2(36),
    CONSTRAINT PK_EMPRESA PRIMARY KEY (EMPRESA_ID),
    CONSTRAINT UQ_EMPRESA_RUT UNIQUE (RUT),
    CONSTRAINT CK_EMPRESA_1 CHECK (ESTADO IN ('ACTIVA','SUSPENDIDA'))
);
COMMENT ON TABLE EMPRESA IS 'Cliente de la plataforma (tenant)';
COMMENT ON COLUMN EMPRESA.EMPRESA_ID IS 'Identificador de la empresa';
COMMENT ON COLUMN EMPRESA.RUT IS 'RUT de la empresa con dígito verificador (76.123.456-7)';
COMMENT ON COLUMN EMPRESA.RAZON_SOCIAL IS 'Razón social';
COMMENT ON COLUMN EMPRESA.NOMBRE_FANTASIA IS 'Nombre comercial';
COMMENT ON COLUMN EMPRESA.CORREO_CONTACTO IS 'Correo del administrador principal';
COMMENT ON COLUMN EMPRESA.TELEFONO IS 'Teléfono de contacto';
COMMENT ON COLUMN EMPRESA.ESTADO IS 'Estado de la cuenta';
COMMENT ON COLUMN EMPRESA.CREADO_EN IS 'Fecha y hora de creación';
COMMENT ON COLUMN EMPRESA.CREADO_POR IS 'OID de Entra External ID de quien creó el registro';
COMMENT ON COLUMN EMPRESA.ACTUALIZADO_EN IS 'Fecha y hora de la última modificación';
COMMENT ON COLUMN EMPRESA.ACTUALIZADO_POR IS 'OID de quien hizo la última modificación';

-- ---------------------------------------------------------------------
-- SUCURSAL: Local o sede de una empresa
-- ---------------------------------------------------------------------
CREATE TABLE SUCURSAL (
    SUCURSAL_ID                NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    EMPRESA_ID                 NUMBER(19) NOT NULL,
    CODIGO                     VARCHAR2(10) NOT NULL,
    NOMBRE                     VARCHAR2(80) NOT NULL,
    DIRECCION                  VARCHAR2(150) NOT NULL,
    COMUNA                     VARCHAR2(60) NOT NULL,
    REGION_CODIGO              VARCHAR2(5) NOT NULL,
    HORA_APERTURA              VARCHAR2(5) NOT NULL,
    HORA_CIERRE                VARCHAR2(5) NOT NULL,
    ESTADO                     VARCHAR2(10) DEFAULT 'ACTIVA' NOT NULL,
    CREADO_EN                  TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CREADO_POR                 VARCHAR2(36) NOT NULL,
    ACTUALIZADO_EN             TIMESTAMP WITH TIME ZONE,
    ACTUALIZADO_POR            VARCHAR2(36),
    CONSTRAINT PK_SUCURSAL PRIMARY KEY (SUCURSAL_ID),
    CONSTRAINT FK_SUC_EMP_EMPRES FOREIGN KEY (EMPRESA_ID) REFERENCES EMPRESA (EMPRESA_ID),
    CONSTRAINT FK_SUC_REG_REGION FOREIGN KEY (REGION_CODIGO) REFERENCES REGION (REGION_CODIGO),
    CONSTRAINT CK_SUCURSAL_1 CHECK (REGEXP_LIKE(HORA_APERTURA, '^([01][0-9]|2[0-3]):[0-5][0-9]$')),
    CONSTRAINT CK_SUCURSAL_2 CHECK (REGEXP_LIKE(HORA_CIERRE, '^([01][0-9]|2[0-3]):[0-5][0-9]$')),
    CONSTRAINT CK_SUCURSAL_3 CHECK (ESTADO IN ('ACTIVA','INACTIVA')),
    CONSTRAINT UQ_SUCURSAL_1 UNIQUE (EMPRESA_ID, CODIGO),
    CONSTRAINT UQ_SUCURSAL_2 UNIQUE (EMPRESA_ID, NOMBRE),
    CONSTRAINT CK_SUCURSAL_4 CHECK (HORA_CIERRE > HORA_APERTURA)
);
COMMENT ON TABLE SUCURSAL IS 'Local o sede de una empresa';
COMMENT ON COLUMN SUCURSAL.SUCURSAL_ID IS 'Identificador de la sucursal';
COMMENT ON COLUMN SUCURSAL.EMPRESA_ID IS 'Empresa a la que pertenece';
COMMENT ON COLUMN SUCURSAL.CODIGO IS 'Código corto único dentro de la empresa (CEN, MAI)';
COMMENT ON COLUMN SUCURSAL.NOMBRE IS 'Nombre de la sucursal';
COMMENT ON COLUMN SUCURSAL.DIRECCION IS 'Calle y número';
COMMENT ON COLUMN SUCURSAL.COMUNA IS 'Comuna';
COMMENT ON COLUMN SUCURSAL.REGION_CODIGO IS 'Región (define los feriados regionales)';
COMMENT ON COLUMN SUCURSAL.HORA_APERTURA IS 'Hora de apertura HH24:MI';
COMMENT ON COLUMN SUCURSAL.HORA_CIERRE IS 'Hora de cierre HH24:MI';
COMMENT ON COLUMN SUCURSAL.ESTADO IS 'Estado de la sucursal';
COMMENT ON COLUMN SUCURSAL.CREADO_EN IS 'Fecha y hora de creación';
COMMENT ON COLUMN SUCURSAL.CREADO_POR IS 'OID de Entra External ID de quien creó el registro';
COMMENT ON COLUMN SUCURSAL.ACTUALIZADO_EN IS 'Fecha y hora de la última modificación';
COMMENT ON COLUMN SUCURSAL.ACTUALIZADO_POR IS 'OID de quien hizo la última modificación';
CREATE INDEX IX_SUC_REGION_CODIGO ON SUCURSAL (REGION_CODIGO);

-- ---------------------------------------------------------------------
-- EQUIPO: Equipo o área dentro de una sucursal
-- ---------------------------------------------------------------------
CREATE TABLE EQUIPO (
    EQUIPO_ID                  NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    EMPRESA_ID                 NUMBER(19) NOT NULL,
    SUCURSAL_ID                NUMBER(19) NOT NULL,
    NOMBRE                     VARCHAR2(80) NOT NULL,
    DESCRIPCION                VARCHAR2(300),
    ESTADO                     VARCHAR2(10) DEFAULT 'ACTIVO' NOT NULL,
    CREADO_EN                  TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CREADO_POR                 VARCHAR2(36) NOT NULL,
    ACTUALIZADO_EN             TIMESTAMP WITH TIME ZONE,
    ACTUALIZADO_POR            VARCHAR2(36),
    CONSTRAINT PK_EQUIPO PRIMARY KEY (EQUIPO_ID),
    CONSTRAINT FK_EQU_SUC_SUCURS FOREIGN KEY (SUCURSAL_ID) REFERENCES SUCURSAL (SUCURSAL_ID),
    CONSTRAINT CK_EQUIPO_1 CHECK (ESTADO IN ('ACTIVO','INACTIVO')),
    CONSTRAINT UQ_EQUIPO_1 UNIQUE (SUCURSAL_ID, NOMBRE)
);
COMMENT ON TABLE EQUIPO IS 'Equipo o área dentro de una sucursal';
COMMENT ON COLUMN EQUIPO.EQUIPO_ID IS 'Identificador del equipo';
COMMENT ON COLUMN EQUIPO.EMPRESA_ID IS 'Empresa dueña del dato (multiempresa)';
COMMENT ON COLUMN EQUIPO.SUCURSAL_ID IS 'Sucursal a la que pertenece';
COMMENT ON COLUMN EQUIPO.NOMBRE IS 'Nombre del equipo (único en la sucursal)';
COMMENT ON COLUMN EQUIPO.DESCRIPCION IS 'Descripción breve';
COMMENT ON COLUMN EQUIPO.ESTADO IS 'Estado del equipo';
COMMENT ON COLUMN EQUIPO.CREADO_EN IS 'Fecha y hora de creación';
COMMENT ON COLUMN EQUIPO.CREADO_POR IS 'OID de Entra External ID de quien creó el registro';
COMMENT ON COLUMN EQUIPO.ACTUALIZADO_EN IS 'Fecha y hora de la última modificación';
COMMENT ON COLUMN EQUIPO.ACTUALIZADO_POR IS 'OID de quien hizo la última modificación';
CREATE INDEX IX_EQU_EMPRESA_ID ON EQUIPO (EMPRESA_ID);

-- ---------------------------------------------------------------------
-- COORDINADOR_EQUIPO: Asignación vigente o histórica de coordinadores a un equipo
-- ---------------------------------------------------------------------
CREATE TABLE COORDINADOR_EQUIPO (
    COORDINADOR_EQUIPO_ID      NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    EMPRESA_ID                 NUMBER(19) NOT NULL,
    EQUIPO_ID                  NUMBER(19) NOT NULL,
    EMPLEADO_ID                NUMBER(19) NOT NULL,
    VIGENTE_DESDE              DATE NOT NULL,
    VIGENTE_HASTA              DATE,
    CREADO_EN                  TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CREADO_POR                 VARCHAR2(36) NOT NULL,
    ACTUALIZADO_EN             TIMESTAMP WITH TIME ZONE,
    ACTUALIZADO_POR            VARCHAR2(36),
    CONSTRAINT PK_COORDINADOR_EQUIPO PRIMARY KEY (COORDINADOR_EQUIPO_ID),
    CONSTRAINT FK_COOEQU_EQU_EQUIPO FOREIGN KEY (EQUIPO_ID) REFERENCES EQUIPO (EQUIPO_ID),
    CONSTRAINT UQ_COORDINADOR_EQUIPO_1 UNIQUE (EQUIPO_ID, EMPLEADO_ID, VIGENTE_DESDE),
    CONSTRAINT CK_COORDINADOR_EQUIPO_1 CHECK (VIGENTE_HASTA IS NULL OR VIGENTE_HASTA >= VIGENTE_DESDE)
);
COMMENT ON TABLE COORDINADOR_EQUIPO IS 'Asignación vigente o histórica de coordinadores a un equipo';
COMMENT ON COLUMN COORDINADOR_EQUIPO.COORDINADOR_EQUIPO_ID IS 'Identificador de la asignación';
COMMENT ON COLUMN COORDINADOR_EQUIPO.EMPRESA_ID IS 'Empresa dueña del dato (multiempresa)';
COMMENT ON COLUMN COORDINADOR_EQUIPO.EQUIPO_ID IS 'Equipo coordinado';
COMMENT ON COLUMN COORDINADOR_EQUIPO.EMPLEADO_ID IS 'Empleado con rol Coordinador (referencia lógica)';
COMMENT ON COLUMN COORDINADOR_EQUIPO.VIGENTE_DESDE IS 'Inicio de la coordinación';
COMMENT ON COLUMN COORDINADOR_EQUIPO.VIGENTE_HASTA IS 'Fin de la coordinación, o nulo si está vigente';
COMMENT ON COLUMN COORDINADOR_EQUIPO.CREADO_EN IS 'Fecha y hora de creación';
COMMENT ON COLUMN COORDINADOR_EQUIPO.CREADO_POR IS 'OID de Entra External ID de quien creó el registro';
COMMENT ON COLUMN COORDINADOR_EQUIPO.ACTUALIZADO_EN IS 'Fecha y hora de la última modificación';
COMMENT ON COLUMN COORDINADOR_EQUIPO.ACTUALIZADO_POR IS 'OID de quien hizo la última modificación';
CREATE INDEX IX_COOEQU_EMPRESA_ID ON COORDINADOR_EQUIPO (EMPRESA_ID);
CREATE INDEX IX_COOEQU_EMPLEADO_ID ON COORDINADOR_EQUIPO (EMPLEADO_ID);

-- ---------------------------------------------------------------------
-- FERIADO: Feriados nacionales, regionales y días especiales de una sucursal
-- ---------------------------------------------------------------------
CREATE TABLE FERIADO (
    FERIADO_ID                 NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    EMPRESA_ID                 NUMBER(19),
    SUCURSAL_ID                NUMBER(19),
    REGION_CODIGO              VARCHAR2(5),
    FECHA                      DATE NOT NULL,
    NOMBRE                     VARCHAR2(100) NOT NULL,
    ALCANCE                    VARCHAR2(10) NOT NULL,
    IRRENUNCIABLE              NUMBER(1) DEFAULT 0 NOT NULL,
    CREADO_EN                  TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CREADO_POR                 VARCHAR2(36) NOT NULL,
    ACTUALIZADO_EN             TIMESTAMP WITH TIME ZONE,
    ACTUALIZADO_POR            VARCHAR2(36),
    CONSTRAINT PK_FERIADO PRIMARY KEY (FERIADO_ID),
    CONSTRAINT FK_FER_EMP_EMPRES FOREIGN KEY (EMPRESA_ID) REFERENCES EMPRESA (EMPRESA_ID),
    CONSTRAINT FK_FER_SUC_SUCURS FOREIGN KEY (SUCURSAL_ID) REFERENCES SUCURSAL (SUCURSAL_ID),
    CONSTRAINT FK_FER_REG_REGION FOREIGN KEY (REGION_CODIGO) REFERENCES REGION (REGION_CODIGO),
    CONSTRAINT CK_FERIADO_1 CHECK (ALCANCE IN ('NACIONAL','REGIONAL','SUCURSAL')),
    CONSTRAINT CK_FERIADO_2 CHECK (IRRENUNCIABLE IN (0,1)),
    CONSTRAINT UQ_FERIADO_1 UNIQUE (FECHA, ALCANCE, REGION_CODIGO, SUCURSAL_ID),
    CONSTRAINT CK_FERIADO_3 CHECK ((ALCANCE = 'NACIONAL' AND REGION_CODIGO IS NULL AND SUCURSAL_ID IS NULL AND EMPRESA_ID IS NULL) OR (ALCANCE = 'REGIONAL' AND REGION_CODIGO IS NOT NULL AND SUCURSAL_ID IS NULL AND EMPRESA_ID IS NULL) OR (ALCANCE = 'SUCURSAL' AND SUCURSAL_ID IS NOT NULL AND EMPRESA_ID IS NOT NULL))
);
COMMENT ON TABLE FERIADO IS 'Feriados nacionales, regionales y días especiales de una sucursal';
COMMENT ON COLUMN FERIADO.FERIADO_ID IS 'Identificador del feriado';
COMMENT ON COLUMN FERIADO.EMPRESA_ID IS 'Solo para días especiales de una sucursal';
COMMENT ON COLUMN FERIADO.SUCURSAL_ID IS 'Sucursal del día especial';
COMMENT ON COLUMN FERIADO.REGION_CODIGO IS 'Región del feriado regional';
COMMENT ON COLUMN FERIADO.FECHA IS 'Día del feriado';
COMMENT ON COLUMN FERIADO.NOMBRE IS 'Nombre del feriado o día especial';
COMMENT ON COLUMN FERIADO.ALCANCE IS 'Alcance del feriado';
COMMENT ON COLUMN FERIADO.IRRENUNCIABLE IS '1 si es feriado irrenunciable';
COMMENT ON COLUMN FERIADO.CREADO_EN IS 'Fecha y hora de creación';
COMMENT ON COLUMN FERIADO.CREADO_POR IS 'OID de Entra External ID de quien creó el registro';
COMMENT ON COLUMN FERIADO.ACTUALIZADO_EN IS 'Fecha y hora de la última modificación';
COMMENT ON COLUMN FERIADO.ACTUALIZADO_POR IS 'OID de quien hizo la última modificación';
CREATE INDEX IX_FER_EMPRESA_ID ON FERIADO (EMPRESA_ID);
CREATE INDEX IX_FER_SUCURSAL_ID ON FERIADO (SUCURSAL_ID);
CREATE INDEX IX_FER_REGION_CODIGO ON FERIADO (REGION_CODIGO);

