-- ---------------------------------------------------------------------
-- EMPLEADO: Ficha del trabajador y su ubicación actual
-- ---------------------------------------------------------------------
CREATE TABLE EMPLEADO (
    EMPLEADO_ID                NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    EMPRESA_ID                 NUMBER(19) NOT NULL,
    SUCURSAL_ID                NUMBER(19) NOT NULL,
    EQUIPO_ID                  NUMBER(19),
    USUARIO_OID                VARCHAR2(36),
    RUT                        VARCHAR2(12) NOT NULL,
    NOMBRES                    VARCHAR2(80) NOT NULL,
    APELLIDOS                  VARCHAR2(80) NOT NULL,
    CORREO                     VARCHAR2(254) NOT NULL,
    TELEFONO                   VARCHAR2(20),
    CARGO                      VARCHAR2(80),
    ROL                        VARCHAR2(15) DEFAULT 'EMPLEADO' NOT NULL,
    FECHA_INGRESO_ROTACION     DATE NOT NULL,
    ESTADO                     VARCHAR2(10) DEFAULT 'ACTIVO' NOT NULL,
    FECHA_DESACTIVACION        DATE,
    MOTIVO_DESACTIVACION       VARCHAR2(200),
    CREADO_EN                  TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CREADO_POR                 VARCHAR2(36) NOT NULL,
    ACTUALIZADO_EN             TIMESTAMP WITH TIME ZONE,
    ACTUALIZADO_POR            VARCHAR2(36),
    CONSTRAINT PK_EMPLEADO PRIMARY KEY (EMPLEADO_ID),
    CONSTRAINT UQ_EMPLEADO_USUARIO_OID UNIQUE (USUARIO_OID),
    CONSTRAINT CK_EMPLEADO_1 CHECK (ROL IN ('ADMINISTRADOR','COORDINADOR','EMPLEADO')),
    CONSTRAINT CK_EMPLEADO_2 CHECK (ESTADO IN ('ACTIVO','INACTIVO')),
    CONSTRAINT UQ_EMPLEADO_1 UNIQUE (EMPRESA_ID, RUT),
    CONSTRAINT UQ_EMPLEADO_2 UNIQUE (EMPRESA_ID, CORREO),
    CONSTRAINT CK_EMPLEADO_3 CHECK (ESTADO = 'ACTIVO' OR FECHA_DESACTIVACION IS NOT NULL)
);
COMMENT ON TABLE EMPLEADO IS 'Ficha del trabajador y su ubicación actual';
COMMENT ON COLUMN EMPLEADO.EMPLEADO_ID IS 'Identificador del empleado';
COMMENT ON COLUMN EMPLEADO.EMPRESA_ID IS 'Empresa dueña del dato (multiempresa)';
COMMENT ON COLUMN EMPLEADO.SUCURSAL_ID IS 'Sucursal actual';
COMMENT ON COLUMN EMPLEADO.EQUIPO_ID IS 'Equipo actual, o nulo si aún no tiene equipo';
COMMENT ON COLUMN EMPLEADO.USUARIO_OID IS 'Object ID del usuario en Entra External ID';
COMMENT ON COLUMN EMPLEADO.RUT IS 'RUT del trabajador';
COMMENT ON COLUMN EMPLEADO.NOMBRES IS 'Nombres';
COMMENT ON COLUMN EMPLEADO.APELLIDOS IS 'Apellidos';
COMMENT ON COLUMN EMPLEADO.CORREO IS 'Correo para avisos e inicio de sesión';
COMMENT ON COLUMN EMPLEADO.TELEFONO IS 'Teléfono móvil';
COMMENT ON COLUMN EMPLEADO.CARGO IS 'Cargo';
COMMENT ON COLUMN EMPLEADO.ROL IS 'Rol de aplicación (espejo del app role de Entra)';
COMMENT ON COLUMN EMPLEADO.FECHA_INGRESO_ROTACION IS 'Desde cuándo cuenta para la rotación';
COMMENT ON COLUMN EMPLEADO.ESTADO IS 'Estado del trabajador';
COMMENT ON COLUMN EMPLEADO.FECHA_DESACTIVACION IS 'Fecha en que deja la rotación';
COMMENT ON COLUMN EMPLEADO.MOTIVO_DESACTIVACION IS 'Motivo de la desactivación';
COMMENT ON COLUMN EMPLEADO.CREADO_EN IS 'Fecha y hora de creación';
COMMENT ON COLUMN EMPLEADO.CREADO_POR IS 'OID de Entra External ID de quien creó el registro';
COMMENT ON COLUMN EMPLEADO.ACTUALIZADO_EN IS 'Fecha y hora de la última modificación';
COMMENT ON COLUMN EMPLEADO.ACTUALIZADO_POR IS 'OID de quien hizo la última modificación';
CREATE INDEX IX_EMP_SUCURSAL_ID ON EMPLEADO (SUCURSAL_ID);
CREATE INDEX IX_EMP_EQUIPO_ID ON EMPLEADO (EQUIPO_ID);

-- ---------------------------------------------------------------------
-- TRASLADO: Historial de cambios de sucursal o equipo
-- ---------------------------------------------------------------------
CREATE TABLE TRASLADO (
    TRASLADO_ID                NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    EMPRESA_ID                 NUMBER(19) NOT NULL,
    EMPLEADO_ID                NUMBER(19) NOT NULL,
    SUCURSAL_ORIGEN_ID         NUMBER(19) NOT NULL,
    SUCURSAL_DESTINO_ID        NUMBER(19) NOT NULL,
    EQUIPO_ORIGEN_ID           NUMBER(19),
    EQUIPO_DESTINO_ID          NUMBER(19),
    FECHA_EFECTIVA             DATE NOT NULL,
    MOTIVO                     VARCHAR2(200),
    CREADO_EN                  TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CREADO_POR                 VARCHAR2(36) NOT NULL,
    ACTUALIZADO_EN             TIMESTAMP WITH TIME ZONE,
    ACTUALIZADO_POR            VARCHAR2(36),
    CONSTRAINT PK_TRASLADO PRIMARY KEY (TRASLADO_ID),
    CONSTRAINT FK_TRA_EMP_EMPLEA FOREIGN KEY (EMPLEADO_ID) REFERENCES EMPLEADO (EMPLEADO_ID),
    CONSTRAINT CK_TRASLADO_1 CHECK (SUCURSAL_ORIGEN_ID <> SUCURSAL_DESTINO_ID OR NVL(EQUIPO_ORIGEN_ID,-1) <> NVL(EQUIPO_DESTINO_ID,-1))
);
COMMENT ON TABLE TRASLADO IS 'Historial de cambios de sucursal o equipo';
COMMENT ON COLUMN TRASLADO.TRASLADO_ID IS 'Identificador del traslado';
COMMENT ON COLUMN TRASLADO.EMPRESA_ID IS 'Empresa dueña del dato (multiempresa)';
COMMENT ON COLUMN TRASLADO.EMPLEADO_ID IS 'Empleado trasladado';
COMMENT ON COLUMN TRASLADO.SUCURSAL_ORIGEN_ID IS 'Sucursal de origen';
COMMENT ON COLUMN TRASLADO.SUCURSAL_DESTINO_ID IS 'Sucursal de destino';
COMMENT ON COLUMN TRASLADO.EQUIPO_ORIGEN_ID IS 'Equipo de origen';
COMMENT ON COLUMN TRASLADO.EQUIPO_DESTINO_ID IS 'Equipo de destino';
COMMENT ON COLUMN TRASLADO.FECHA_EFECTIVA IS 'Desde cuándo rige el traslado';
COMMENT ON COLUMN TRASLADO.MOTIVO IS 'Motivo del traslado';
COMMENT ON COLUMN TRASLADO.CREADO_EN IS 'Fecha y hora de creación';
COMMENT ON COLUMN TRASLADO.CREADO_POR IS 'OID de Entra External ID de quien creó el registro';
COMMENT ON COLUMN TRASLADO.ACTUALIZADO_EN IS 'Fecha y hora de la última modificación';
COMMENT ON COLUMN TRASLADO.ACTUALIZADO_POR IS 'OID de quien hizo la última modificación';
CREATE INDEX IX_TRA_EMPRESA_ID ON TRASLADO (EMPRESA_ID);
CREATE INDEX IX_TRA_EMPLEADO_ID ON TRASLADO (EMPLEADO_ID);
CREATE INDEX IX_TRA_SUCURSAL_ORIGEN_ID ON TRASLADO (SUCURSAL_ORIGEN_ID);
CREATE INDEX IX_TRA_SUCURSAL_DESTINO_ID ON TRASLADO (SUCURSAL_DESTINO_ID);
CREATE INDEX IX_TRA_EQUIPO_ORIGEN_ID ON TRASLADO (EQUIPO_ORIGEN_ID);
CREATE INDEX IX_TRA_EQUIPO_DESTINO_ID ON TRASLADO (EQUIPO_DESTINO_ID);

-- ---------------------------------------------------------------------
-- DISPONIBILIDAD: Fechas en que el empleado no puede cubrir turno
-- ---------------------------------------------------------------------
CREATE TABLE DISPONIBILIDAD (
    DISPONIBILIDAD_ID          NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    EMPRESA_ID                 NUMBER(19) NOT NULL,
    SUCURSAL_ID                NUMBER(19) NOT NULL,
    EMPLEADO_ID                NUMBER(19) NOT NULL,
    FECHA_DESDE                DATE NOT NULL,
    FECHA_HASTA                DATE NOT NULL,
    TIPO                       VARCHAR2(12) NOT NULL,
    MOTIVO                     VARCHAR2(200),
    CREADO_EN                  TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CREADO_POR                 VARCHAR2(36) NOT NULL,
    ACTUALIZADO_EN             TIMESTAMP WITH TIME ZONE,
    ACTUALIZADO_POR            VARCHAR2(36),
    CONSTRAINT PK_DISPONIBILIDAD PRIMARY KEY (DISPONIBILIDAD_ID),
    CONSTRAINT FK_DIS_EMP_EMPLEA FOREIGN KEY (EMPLEADO_ID) REFERENCES EMPLEADO (EMPLEADO_ID),
    CONSTRAINT CK_DISPONIBILIDAD_1 CHECK (TIPO IN ('NO_PUEDE','VACACIONES','LICENCIA','PERMISO')),
    CONSTRAINT CK_DISPONIBILIDAD_2 CHECK (FECHA_HASTA >= FECHA_DESDE)
);
COMMENT ON TABLE DISPONIBILIDAD IS 'Fechas en que el empleado no puede cubrir turno';
COMMENT ON COLUMN DISPONIBILIDAD.DISPONIBILIDAD_ID IS 'Identificador del registro';
COMMENT ON COLUMN DISPONIBILIDAD.EMPRESA_ID IS 'Empresa dueña del dato (multiempresa)';
COMMENT ON COLUMN DISPONIBILIDAD.SUCURSAL_ID IS 'Sucursal del empleado al registrar';
COMMENT ON COLUMN DISPONIBILIDAD.EMPLEADO_ID IS 'Empleado';
COMMENT ON COLUMN DISPONIBILIDAD.FECHA_DESDE IS 'Primer día sin disponibilidad';
COMMENT ON COLUMN DISPONIBILIDAD.FECHA_HASTA IS 'Último día sin disponibilidad';
COMMENT ON COLUMN DISPONIBILIDAD.TIPO IS 'Tipo de restricción';
COMMENT ON COLUMN DISPONIBILIDAD.MOTIVO IS 'Detalle opcional (sin datos de salud)';
COMMENT ON COLUMN DISPONIBILIDAD.CREADO_EN IS 'Fecha y hora de creación';
COMMENT ON COLUMN DISPONIBILIDAD.CREADO_POR IS 'OID de Entra External ID de quien creó el registro';
COMMENT ON COLUMN DISPONIBILIDAD.ACTUALIZADO_EN IS 'Fecha y hora de la última modificación';
COMMENT ON COLUMN DISPONIBILIDAD.ACTUALIZADO_POR IS 'OID de quien hizo la última modificación';
CREATE INDEX IX_DIS_EMPRESA_ID ON DISPONIBILIDAD (EMPRESA_ID);
CREATE INDEX IX_DIS_SUCURSAL_ID ON DISPONIBILIDAD (SUCURSAL_ID);
CREATE INDEX IX_DIS_EMPLEADO_ID ON DISPONIBILIDAD (EMPLEADO_ID);

-- ---------------------------------------------------------------------
-- OUTBOX_EVENTO: Eventos pendientes de publicar en Service Bus (patrón outbox)
-- ---------------------------------------------------------------------
CREATE TABLE OUTBOX_EVENTO (
    EVENTO_ID                  VARCHAR2(36) NOT NULL,
    EMPRESA_ID                 NUMBER(19) NOT NULL,
    TIPO_EVENTO                VARCHAR2(40) NOT NULL,
    AGREGADO_ID                NUMBER(19) NOT NULL,
    CARGA                      CLOB NOT NULL,
    ESTADO                     VARCHAR2(10) DEFAULT 'PENDIENTE' NOT NULL,
    INTENTOS                   NUMBER(3) DEFAULT 0 NOT NULL,
    CREADO_EN                  TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    PUBLICADO_EN               TIMESTAMP WITH TIME ZONE,
    CONSTRAINT PK_OUTBOX_EVENTO PRIMARY KEY (EVENTO_ID),
    CONSTRAINT CK_OUTBOX_EVENTO_1 CHECK (CARGA IS JSON),
    CONSTRAINT CK_OUTBOX_EVENTO_2 CHECK (ESTADO IN ('PENDIENTE','PUBLICADO','ERROR'))
);
COMMENT ON TABLE OUTBOX_EVENTO IS 'Eventos pendientes de publicar en Service Bus (patrón outbox)';
COMMENT ON COLUMN OUTBOX_EVENTO.EVENTO_ID IS 'UUID del evento (clave de idempotencia)';
COMMENT ON COLUMN OUTBOX_EVENTO.EMPRESA_ID IS 'Empresa dueña del dato (multiempresa)';
COMMENT ON COLUMN OUTBOX_EVENTO.TIPO_EVENTO IS 'EmpleadoTrasladado, EmpleadoDesactivado, etc.';
COMMENT ON COLUMN OUTBOX_EVENTO.AGREGADO_ID IS 'Identificador del registro que originó el evento';
COMMENT ON COLUMN OUTBOX_EVENTO.CARGA IS 'Contenido del evento en JSON';
COMMENT ON COLUMN OUTBOX_EVENTO.ESTADO IS 'Estado de publicación';
COMMENT ON COLUMN OUTBOX_EVENTO.INTENTOS IS 'Reintentos de publicación';
COMMENT ON COLUMN OUTBOX_EVENTO.CREADO_EN IS 'Momento de creación';
COMMENT ON COLUMN OUTBOX_EVENTO.PUBLICADO_EN IS 'Momento de publicación';
CREATE INDEX IX_OUTEVE_EMPRESA_ID ON OUTBOX_EVENTO (EMPRESA_ID);

