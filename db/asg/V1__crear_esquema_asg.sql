-- ---------------------------------------------------------------------
-- REGLA_ASIGNACION: Reglas del algoritmo y su prioridad por empresa o equipo
-- ---------------------------------------------------------------------
CREATE TABLE REGLA_ASIGNACION (
    REGLA_ID                   NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    EMPRESA_ID                 NUMBER(19) NOT NULL,
    EQUIPO_ID                  NUMBER(19),
    CODIGO                     VARCHAR2(30) NOT NULL,
    PRIORIDAD                  NUMBER(2) NOT NULL,
    ES_DURA                    NUMBER(1) DEFAULT 1 NOT NULL,
    PARAMETROS                 CLOB,
    ACTIVA                     NUMBER(1) DEFAULT 1 NOT NULL,
    CREADO_EN                  TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CREADO_POR                 VARCHAR2(36) NOT NULL,
    ACTUALIZADO_EN             TIMESTAMP WITH TIME ZONE,
    ACTUALIZADO_POR            VARCHAR2(36),
    CONSTRAINT PK_REGLA_ASIGNACION PRIMARY KEY (REGLA_ID),
    CONSTRAINT CK_REGLA_ASIGNACION_1 CHECK (CODIGO IN ('MAYOR_DEFICIT','SIN_CHOQUE_DISPONIBILIDAD','ROTACION_PAREJAS','DESCANSO_MINIMO','MAX_TURNOS_MES')),
    CONSTRAINT CK_REGLA_ASIGNACION_2 CHECK (PRIORIDAD BETWEEN 1 AND 99),
    CONSTRAINT CK_REGLA_ASIGNACION_3 CHECK (ES_DURA IN (0,1)),
    CONSTRAINT CK_REGLA_ASIGNACION_4 CHECK (PARAMETROS IS JSON),
    CONSTRAINT CK_REGLA_ASIGNACION_5 CHECK (ACTIVA IN (0,1)),
    CONSTRAINT UQ_REGLA_ASIGNACION_1 UNIQUE (EMPRESA_ID, EQUIPO_ID, CODIGO)
);
COMMENT ON TABLE REGLA_ASIGNACION IS 'Reglas del algoritmo y su prioridad por empresa o equipo';
COMMENT ON COLUMN REGLA_ASIGNACION.REGLA_ID IS 'Identificador de la regla';
COMMENT ON COLUMN REGLA_ASIGNACION.EMPRESA_ID IS 'Empresa dueña del dato (multiempresa)';
COMMENT ON COLUMN REGLA_ASIGNACION.EQUIPO_ID IS 'Equipo, o nulo si aplica a toda la empresa';
COMMENT ON COLUMN REGLA_ASIGNACION.CODIGO IS 'Regla';
COMMENT ON COLUMN REGLA_ASIGNACION.PRIORIDAD IS 'Orden de aplicación (1 = primero)';
COMMENT ON COLUMN REGLA_ASIGNACION.ES_DURA IS '1 = no se puede romper, 0 = preferencia';
COMMENT ON COLUMN REGLA_ASIGNACION.PARAMETROS IS 'Parámetros de la regla en JSON';
COMMENT ON COLUMN REGLA_ASIGNACION.ACTIVA IS '1 si la regla está activa';
COMMENT ON COLUMN REGLA_ASIGNACION.CREADO_EN IS 'Fecha y hora de creación';
COMMENT ON COLUMN REGLA_ASIGNACION.CREADO_POR IS 'OID de Entra External ID de quien creó el registro';
COMMENT ON COLUMN REGLA_ASIGNACION.ACTUALIZADO_EN IS 'Fecha y hora de la última modificación';
COMMENT ON COLUMN REGLA_ASIGNACION.ACTUALIZADO_POR IS 'OID de quien hizo la última modificación';
CREATE INDEX IX_REGASI_EQUIPO_ID ON REGLA_ASIGNACION (EQUIPO_ID);

-- ---------------------------------------------------------------------
-- PROPUESTA: Resultado de una ejecución del algoritmo para un equipo y mes
-- ---------------------------------------------------------------------
CREATE TABLE PROPUESTA (
    PROPUESTA_ID               NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    EMPRESA_ID                 NUMBER(19) NOT NULL,
    SUCURSAL_ID                NUMBER(19) NOT NULL,
    EQUIPO_ID                  NUMBER(19) NOT NULL,
    ANIO                       NUMBER(4) NOT NULL,
    MES                        NUMBER(2) NOT NULL,
    ESTADO                     VARCHAR2(10) DEFAULT 'GENERADA' NOT NULL,
    TOTAL_TURNOS_PERSONA       NUMBER(5) NOT NULL,
    SUMA_CAPACIDAD             NUMBER(6) NOT NULL,
    DESVIACION_MAXIMA          NUMBER(5,2) NOT NULL,
    PCT_EXCEPCIONES            NUMBER(5,2) NOT NULL,
    DURACION_MS                NUMBER(8),
    GENERADA_POR               VARCHAR2(36) NOT NULL,
    GENERADA_EN                TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_PROPUESTA PRIMARY KEY (PROPUESTA_ID),
    CONSTRAINT CK_PROPUESTA_1 CHECK (MES BETWEEN 1 AND 12),
    CONSTRAINT CK_PROPUESTA_2 CHECK (ESTADO IN ('GENERADA','AJUSTADA','PUBLICADA','DESCARTADA'))
);
COMMENT ON TABLE PROPUESTA IS 'Resultado de una ejecución del algoritmo para un equipo y mes';
COMMENT ON COLUMN PROPUESTA.PROPUESTA_ID IS 'Identificador de la propuesta';
COMMENT ON COLUMN PROPUESTA.EMPRESA_ID IS 'Empresa dueña del dato (multiempresa)';
COMMENT ON COLUMN PROPUESTA.SUCURSAL_ID IS 'Sucursal';
COMMENT ON COLUMN PROPUESTA.EQUIPO_ID IS 'Equipo';
COMMENT ON COLUMN PROPUESTA.ANIO IS 'Año';
COMMENT ON COLUMN PROPUESTA.MES IS 'Mes';
COMMENT ON COLUMN PROPUESTA.ESTADO IS 'Estado';
COMMENT ON COLUMN PROPUESTA.TOTAL_TURNOS_PERSONA IS 'T: total de turnos-persona del período';
COMMENT ON COLUMN PROPUESTA.SUMA_CAPACIDAD IS 'Σc: suma de capacidades del equipo';
COMMENT ON COLUMN PROPUESTA.DESVIACION_MAXIMA IS 'Mayor |d| del equipo (meta ≤ 1)';
COMMENT ON COLUMN PROPUESTA.PCT_EXCEPCIONES IS 'Porcentaje de turnos con excepción (meta ≤ 5 %)';
COMMENT ON COLUMN PROPUESTA.DURACION_MS IS 'Tiempo de cálculo (meta < 10 000 ms)';
COMMENT ON COLUMN PROPUESTA.GENERADA_POR IS 'OID del coordinador';
COMMENT ON COLUMN PROPUESTA.GENERADA_EN IS 'Momento de generación';
CREATE INDEX IX_PRO_EMPRESA_ID ON PROPUESTA (EMPRESA_ID);
CREATE INDEX IX_PRO_SUCURSAL_ID ON PROPUESTA (SUCURSAL_ID);
CREATE INDEX IX_PRO_EQUIPO_ID ON PROPUESTA (EQUIPO_ID);

-- ---------------------------------------------------------------------
-- PROPUESTA_CUOTA: Cálculo de equidad por persona: capacidad, cuota y desviación
-- ---------------------------------------------------------------------
CREATE TABLE PROPUESTA_CUOTA (
    CUOTA_ID                   NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    EMPRESA_ID                 NUMBER(19) NOT NULL,
    PROPUESTA_ID               NUMBER(19) NOT NULL,
    EMPLEADO_ID                NUMBER(19) NOT NULL,
    CAPACIDAD                  NUMBER(4) NOT NULL,
    CUOTA_ESPERADA             NUMBER(6,2) NOT NULL,
    TURNOS_ASIGNADOS           NUMBER(4) NOT NULL,
    DEFICIT_PREVIO             NUMBER(6,2) DEFAULT 0 NOT NULL,
    DESVIACION                 NUMBER(6,2) NOT NULL,
    CONSTRAINT PK_PROPUESTA_CUOTA PRIMARY KEY (CUOTA_ID),
    CONSTRAINT FK_PROCUO_PRO_PROPUE FOREIGN KEY (PROPUESTA_ID) REFERENCES PROPUESTA (PROPUESTA_ID),
    CONSTRAINT CK_PROPUESTA_CUOTA_1 CHECK (CAPACIDAD >= 0),
    CONSTRAINT UQ_PROPUESTA_CUOTA_1 UNIQUE (PROPUESTA_ID, EMPLEADO_ID)
);
COMMENT ON TABLE PROPUESTA_CUOTA IS 'Cálculo de equidad por persona: capacidad, cuota y desviación';
COMMENT ON COLUMN PROPUESTA_CUOTA.CUOTA_ID IS 'Identificador';
COMMENT ON COLUMN PROPUESTA_CUOTA.EMPRESA_ID IS 'Empresa dueña del dato (multiempresa)';
COMMENT ON COLUMN PROPUESTA_CUOTA.PROPUESTA_ID IS 'Propuesta';
COMMENT ON COLUMN PROPUESTA_CUOTA.EMPLEADO_ID IS 'Empleado';
COMMENT ON COLUMN PROPUESTA_CUOTA.CAPACIDAD IS 'c: turnos en que estuvo disponible';
COMMENT ON COLUMN PROPUESTA_CUOTA.CUOTA_ESPERADA IS 'e = T × c / Σc';
COMMENT ON COLUMN PROPUESTA_CUOTA.TURNOS_ASIGNADOS IS 'Turnos asignados en la propuesta';
COMMENT ON COLUMN PROPUESTA_CUOTA.DEFICIT_PREVIO IS 'Déficit acumulado de períodos anteriores';
COMMENT ON COLUMN PROPUESTA_CUOTA.DESVIACION IS 'd = asignados − e';
CREATE INDEX IX_PROCUO_EMPRESA_ID ON PROPUESTA_CUOTA (EMPRESA_ID);
CREATE INDEX IX_PROCUO_EMPLEADO_ID ON PROPUESTA_CUOTA (EMPLEADO_ID);

-- ---------------------------------------------------------------------
-- PROPUESTA_DETALLE: Cada persona propuesta para un turno y fecha
-- ---------------------------------------------------------------------
CREATE TABLE PROPUESTA_DETALLE (
    DETALLE_ID                 NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    EMPRESA_ID                 NUMBER(19) NOT NULL,
    PROPUESTA_ID               NUMBER(19) NOT NULL,
    CONFIG_TURNO_ID            NUMBER(19) NOT NULL,
    FECHA                      DATE NOT NULL,
    EMPLEADO_ID                NUMBER(19) NOT NULL,
    ES_EXCEPCION               NUMBER(1) DEFAULT 0 NOT NULL,
    MOTIVO_EXCEPCION           VARCHAR2(200),
    EDITADO_MANUAL             NUMBER(1) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_PROPUESTA_DETALLE PRIMARY KEY (DETALLE_ID),
    CONSTRAINT FK_PRODET_PRO_PROPUE FOREIGN KEY (PROPUESTA_ID) REFERENCES PROPUESTA (PROPUESTA_ID),
    CONSTRAINT CK_PROPUESTA_DETALLE_1 CHECK (ES_EXCEPCION IN (0,1)),
    CONSTRAINT CK_PROPUESTA_DETALLE_2 CHECK (EDITADO_MANUAL IN (0,1)),
    CONSTRAINT UQ_PROPUESTA_DETALLE_1 UNIQUE (PROPUESTA_ID, CONFIG_TURNO_ID, FECHA, EMPLEADO_ID)
);
COMMENT ON TABLE PROPUESTA_DETALLE IS 'Cada persona propuesta para un turno y fecha';
COMMENT ON COLUMN PROPUESTA_DETALLE.DETALLE_ID IS 'Identificador';
COMMENT ON COLUMN PROPUESTA_DETALLE.EMPRESA_ID IS 'Empresa dueña del dato (multiempresa)';
COMMENT ON COLUMN PROPUESTA_DETALLE.PROPUESTA_ID IS 'Propuesta';
COMMENT ON COLUMN PROPUESTA_DETALLE.CONFIG_TURNO_ID IS 'Turno tipo';
COMMENT ON COLUMN PROPUESTA_DETALLE.FECHA IS 'Fecha';
COMMENT ON COLUMN PROPUESTA_DETALLE.EMPLEADO_ID IS 'Empleado propuesto';
COMMENT ON COLUMN PROPUESTA_DETALLE.ES_EXCEPCION IS '1 si rompe una regla blanda';
COMMENT ON COLUMN PROPUESTA_DETALLE.MOTIVO_EXCEPCION IS 'Causa de la excepción';
COMMENT ON COLUMN PROPUESTA_DETALLE.EDITADO_MANUAL IS '1 si el coordinador lo cambió';
CREATE INDEX IX_PRODET_EMPRESA_ID ON PROPUESTA_DETALLE (EMPRESA_ID);
CREATE INDEX IX_PRODET_CONFIG_TURNO_ID ON PROPUESTA_DETALLE (CONFIG_TURNO_ID);
CREATE INDEX IX_PRODET_EMPLEADO_ID ON PROPUESTA_DETALLE (EMPLEADO_ID);

