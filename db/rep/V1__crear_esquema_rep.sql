-- ---------------------------------------------------------------------
-- RESUMEN_MENSUAL_EMPLEADO: Acumulados y equidad por persona y mes (alimentado por eventos)
-- ---------------------------------------------------------------------
CREATE TABLE RESUMEN_MENSUAL_EMPLEADO (
    RESUMEN_ID                 NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    EMPRESA_ID                 NUMBER(19) NOT NULL,
    SUCURSAL_ID                NUMBER(19) NOT NULL,
    EQUIPO_ID                  NUMBER(19) NOT NULL,
    EMPLEADO_ID                NUMBER(19) NOT NULL,
    NOMBRE_EMPLEADO            VARCHAR2(160) NOT NULL,
    ANIO                       NUMBER(4) NOT NULL,
    MES                        NUMBER(2) NOT NULL,
    TURNOS_ASIGNADOS           NUMBER(4) DEFAULT 0 NOT NULL,
    TURNOS_CUBIERTOS           NUMBER(4) DEFAULT 0 NOT NULL,
    REEMPLAZOS_DADOS           NUMBER(4) DEFAULT 0 NOT NULL,
    REEMPLAZOS_RECIBIDOS       NUMBER(4) DEFAULT 0 NOT NULL,
    CAPACIDAD                  NUMBER(4) DEFAULT 0 NOT NULL,
    CUOTA_ESPERADA             NUMBER(6,2) DEFAULT 0 NOT NULL,
    DESVIACION_ACUMULADA       NUMBER(6,2) DEFAULT 0 NOT NULL,
    ACTUALIZADO_EN             TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_RESUMEN_MENSUAL_EMPLEADO PRIMARY KEY (RESUMEN_ID),
    CONSTRAINT CK_RESUMEN_MENSUAL_EMPLEADO_1 CHECK (MES BETWEEN 1 AND 12),
    CONSTRAINT UQ_RESUMEN_MENSUAL_EMPLEADO_1 UNIQUE (EMPLEADO_ID, EQUIPO_ID, ANIO, MES)
);
COMMENT ON TABLE RESUMEN_MENSUAL_EMPLEADO IS 'Acumulados y equidad por persona y mes (alimentado por eventos)';
COMMENT ON COLUMN RESUMEN_MENSUAL_EMPLEADO.RESUMEN_ID IS 'Identificador';
COMMENT ON COLUMN RESUMEN_MENSUAL_EMPLEADO.EMPRESA_ID IS 'Empresa dueña del dato (multiempresa)';
COMMENT ON COLUMN RESUMEN_MENSUAL_EMPLEADO.SUCURSAL_ID IS 'Sucursal';
COMMENT ON COLUMN RESUMEN_MENSUAL_EMPLEADO.EQUIPO_ID IS 'Equipo';
COMMENT ON COLUMN RESUMEN_MENSUAL_EMPLEADO.EMPLEADO_ID IS 'Empleado';
COMMENT ON COLUMN RESUMEN_MENSUAL_EMPLEADO.NOMBRE_EMPLEADO IS 'Nombre (copia para lectura rápida)';
COMMENT ON COLUMN RESUMEN_MENSUAL_EMPLEADO.ANIO IS 'Año';
COMMENT ON COLUMN RESUMEN_MENSUAL_EMPLEADO.MES IS 'Mes';
COMMENT ON COLUMN RESUMEN_MENSUAL_EMPLEADO.TURNOS_ASIGNADOS IS 'Turnos asignados';
COMMENT ON COLUMN RESUMEN_MENSUAL_EMPLEADO.TURNOS_CUBIERTOS IS 'Turnos realmente cubiertos';
COMMENT ON COLUMN RESUMEN_MENSUAL_EMPLEADO.REEMPLAZOS_DADOS IS 'Veces que cubrió a otro';
COMMENT ON COLUMN RESUMEN_MENSUAL_EMPLEADO.REEMPLAZOS_RECIBIDOS IS 'Veces que fue cubierto';
COMMENT ON COLUMN RESUMEN_MENSUAL_EMPLEADO.CAPACIDAD IS 'c del mes';
COMMENT ON COLUMN RESUMEN_MENSUAL_EMPLEADO.CUOTA_ESPERADA IS 'e del mes';
COMMENT ON COLUMN RESUMEN_MENSUAL_EMPLEADO.DESVIACION_ACUMULADA IS 'd acumulada a la fecha';
COMMENT ON COLUMN RESUMEN_MENSUAL_EMPLEADO.ACTUALIZADO_EN IS 'Última actualización';
CREATE INDEX IX_RESMENEMP_EMPRESA_ID ON RESUMEN_MENSUAL_EMPLEADO (EMPRESA_ID);
CREATE INDEX IX_RESMENEMP_SUCURSAL_ID ON RESUMEN_MENSUAL_EMPLEADO (SUCURSAL_ID);
CREATE INDEX IX_RESMENEMP_EQUIPO_ID ON RESUMEN_MENSUAL_EMPLEADO (EQUIPO_ID);

-- ---------------------------------------------------------------------
-- RESUMEN_SUCURSAL: Indicadores mensuales por sucursal (base del consolidado de empresa)
-- ---------------------------------------------------------------------
CREATE TABLE RESUMEN_SUCURSAL (
    RESUMEN_SUCURSAL_ID        NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    EMPRESA_ID                 NUMBER(19) NOT NULL,
    SUCURSAL_ID                NUMBER(19) NOT NULL,
    NOMBRE_SUCURSAL            VARCHAR2(80) NOT NULL,
    ANIO                       NUMBER(4) NOT NULL,
    MES                        NUMBER(2) NOT NULL,
    TOTAL_TURNOS_PERSONA       NUMBER(6) DEFAULT 0 NOT NULL,
    EMPLEADOS_ACTIVOS          NUMBER(5) DEFAULT 0 NOT NULL,
    PROMEDIO_TURNOS_PERSONA    NUMBER(6,2) DEFAULT 0 NOT NULL,
    DESVIACION_MAXIMA          NUMBER(5,2) DEFAULT 0 NOT NULL,
    EXCEPCIONES                NUMBER(5) DEFAULT 0 NOT NULL,
    REEMPLAZOS_INTERSUCURSAL   NUMBER(5) DEFAULT 0 NOT NULL,
    ACTUALIZADO_EN             TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_RESUMEN_SUCURSAL PRIMARY KEY (RESUMEN_SUCURSAL_ID),
    CONSTRAINT CK_RESUMEN_SUCURSAL_1 CHECK (MES BETWEEN 1 AND 12),
    CONSTRAINT UQ_RESUMEN_SUCURSAL_1 UNIQUE (SUCURSAL_ID, ANIO, MES)
);
COMMENT ON TABLE RESUMEN_SUCURSAL IS 'Indicadores mensuales por sucursal (base del consolidado de empresa)';
COMMENT ON COLUMN RESUMEN_SUCURSAL.RESUMEN_SUCURSAL_ID IS 'Identificador';
COMMENT ON COLUMN RESUMEN_SUCURSAL.EMPRESA_ID IS 'Empresa dueña del dato (multiempresa)';
COMMENT ON COLUMN RESUMEN_SUCURSAL.SUCURSAL_ID IS 'Sucursal';
COMMENT ON COLUMN RESUMEN_SUCURSAL.NOMBRE_SUCURSAL IS 'Nombre (copia para lectura rápida)';
COMMENT ON COLUMN RESUMEN_SUCURSAL.ANIO IS 'Año';
COMMENT ON COLUMN RESUMEN_SUCURSAL.MES IS 'Mes';
COMMENT ON COLUMN RESUMEN_SUCURSAL.TOTAL_TURNOS_PERSONA IS 'Turnos-persona del mes';
COMMENT ON COLUMN RESUMEN_SUCURSAL.EMPLEADOS_ACTIVOS IS 'Empleados en rotación';
COMMENT ON COLUMN RESUMEN_SUCURSAL.PROMEDIO_TURNOS_PERSONA IS 'Promedio mensual por persona';
COMMENT ON COLUMN RESUMEN_SUCURSAL.DESVIACION_MAXIMA IS 'Mayor |d| de la sucursal';
COMMENT ON COLUMN RESUMEN_SUCURSAL.EXCEPCIONES IS 'Turnos con excepción';
COMMENT ON COLUMN RESUMEN_SUCURSAL.REEMPLAZOS_INTERSUCURSAL IS 'Apoyos recibidos desde otras sucursales';
COMMENT ON COLUMN RESUMEN_SUCURSAL.ACTUALIZADO_EN IS 'Última actualización';
CREATE INDEX IX_RESSUC_EMPRESA_ID ON RESUMEN_SUCURSAL (EMPRESA_ID);

-- ---------------------------------------------------------------------
-- EVENTO_PROCESADO: Eventos ya consumidos (idempotencia del consumidor)
-- ---------------------------------------------------------------------
CREATE TABLE EVENTO_PROCESADO (
    EVENTO_ID                  VARCHAR2(36) NOT NULL,
    EMPRESA_ID                 NUMBER(19) NOT NULL,
    TIPO_EVENTO                VARCHAR2(40) NOT NULL,
    ORIGEN                     VARCHAR2(30) NOT NULL,
    PROCESADO_EN               TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_EVENTO_PROCESADO PRIMARY KEY (EVENTO_ID)
);
COMMENT ON TABLE EVENTO_PROCESADO IS 'Eventos ya consumidos (idempotencia del consumidor)';
COMMENT ON COLUMN EVENTO_PROCESADO.EVENTO_ID IS 'UUID del evento recibido';
COMMENT ON COLUMN EVENTO_PROCESADO.EMPRESA_ID IS 'Empresa dueña del dato (multiempresa)';
COMMENT ON COLUMN EVENTO_PROCESADO.TIPO_EVENTO IS 'Tipo de evento';
COMMENT ON COLUMN EVENTO_PROCESADO.ORIGEN IS 'Servicio emisor';
COMMENT ON COLUMN EVENTO_PROCESADO.PROCESADO_EN IS 'Momento de procesamiento';
CREATE INDEX IX_EVEPRO_EMPRESA_ID ON EVENTO_PROCESADO (EMPRESA_ID);

