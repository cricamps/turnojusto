-- ---------------------------------------------------------------------
-- CONFIG_TURNO: Turno tipo de un equipo: día, horario y dotación
-- ---------------------------------------------------------------------
CREATE TABLE CONFIG_TURNO (
    CONFIG_TURNO_ID            NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    EMPRESA_ID                 NUMBER(19) NOT NULL,
    SUCURSAL_ID                NUMBER(19) NOT NULL,
    EQUIPO_ID                  NUMBER(19) NOT NULL,
    NOMBRE                     VARCHAR2(60) NOT NULL,
    DIA_SEMANA                 NUMBER(1) NOT NULL,
    HORA_INICIO                VARCHAR2(5) NOT NULL,
    HORA_FIN                   VARCHAR2(5) NOT NULL,
    PERSONAS_REQUERIDAS        NUMBER(2) NOT NULL,
    VIGENTE_DESDE              DATE NOT NULL,
    VIGENTE_HASTA              DATE,
    ACTIVO                     NUMBER(1) DEFAULT 1 NOT NULL,
    CREADO_EN                  TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CREADO_POR                 VARCHAR2(36) NOT NULL,
    ACTUALIZADO_EN             TIMESTAMP WITH TIME ZONE,
    ACTUALIZADO_POR            VARCHAR2(36),
    CONSTRAINT PK_CONFIG_TURNO PRIMARY KEY (CONFIG_TURNO_ID),
    CONSTRAINT CK_CONFIG_TURNO_1 CHECK (DIA_SEMANA BETWEEN 1 AND 7),
    CONSTRAINT CK_CONFIG_TURNO_2 CHECK (REGEXP_LIKE(HORA_INICIO, '^([01][0-9]|2[0-3]):[0-5][0-9]$')),
    CONSTRAINT CK_CONFIG_TURNO_3 CHECK (REGEXP_LIKE(HORA_FIN, '^([01][0-9]|2[0-3]):[0-5][0-9]$')),
    CONSTRAINT CK_CONFIG_TURNO_4 CHECK (PERSONAS_REQUERIDAS BETWEEN 1 AND 20),
    CONSTRAINT CK_CONFIG_TURNO_5 CHECK (ACTIVO IN (0,1)),
    CONSTRAINT UQ_CONFIG_TURNO_1 UNIQUE (EQUIPO_ID, DIA_SEMANA, HORA_INICIO, VIGENTE_DESDE),
    CONSTRAINT CK_CONFIG_TURNO_6 CHECK (HORA_FIN <> HORA_INICIO),
    CONSTRAINT CK_CONFIG_TURNO_7 CHECK (VIGENTE_HASTA IS NULL OR VIGENTE_HASTA >= VIGENTE_DESDE)
);
COMMENT ON TABLE CONFIG_TURNO IS 'Turno tipo de un equipo: día, horario y dotación';
COMMENT ON COLUMN CONFIG_TURNO.CONFIG_TURNO_ID IS 'Identificador del turno tipo';
COMMENT ON COLUMN CONFIG_TURNO.EMPRESA_ID IS 'Empresa dueña del dato (multiempresa)';
COMMENT ON COLUMN CONFIG_TURNO.SUCURSAL_ID IS 'Sucursal';
COMMENT ON COLUMN CONFIG_TURNO.EQUIPO_ID IS 'Equipo que cubre el turno';
COMMENT ON COLUMN CONFIG_TURNO.NOMBRE IS 'Nombre visible (Turno viernes tarde)';
COMMENT ON COLUMN CONFIG_TURNO.DIA_SEMANA IS '1 = lunes ... 7 = domingo (ISO 8601)';
COMMENT ON COLUMN CONFIG_TURNO.HORA_INICIO IS 'Hora de inicio HH24:MI';
COMMENT ON COLUMN CONFIG_TURNO.HORA_FIN IS 'Hora de término HH24:MI (si es menor que el inicio, cruza la medianoche)';
COMMENT ON COLUMN CONFIG_TURNO.PERSONAS_REQUERIDAS IS 'Dotación por turno';
COMMENT ON COLUMN CONFIG_TURNO.VIGENTE_DESDE IS 'Inicio de vigencia';
COMMENT ON COLUMN CONFIG_TURNO.VIGENTE_HASTA IS 'Fin de vigencia, o nulo si está vigente';
COMMENT ON COLUMN CONFIG_TURNO.ACTIVO IS '1 si el turno está activo';
COMMENT ON COLUMN CONFIG_TURNO.CREADO_EN IS 'Fecha y hora de creación';
COMMENT ON COLUMN CONFIG_TURNO.CREADO_POR IS 'OID de Entra External ID de quien creó el registro';
COMMENT ON COLUMN CONFIG_TURNO.ACTUALIZADO_EN IS 'Fecha y hora de la última modificación';
COMMENT ON COLUMN CONFIG_TURNO.ACTUALIZADO_POR IS 'OID de quien hizo la última modificación';
CREATE INDEX IX_CONTUR_EMPRESA_ID ON CONFIG_TURNO (EMPRESA_ID);
CREATE INDEX IX_CONTUR_SUCURSAL_ID ON CONFIG_TURNO (SUCURSAL_ID);

