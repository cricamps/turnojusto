-- ---------------------------------------------------------------------
-- REEMPLAZO: Solicitud de reemplazo de un turno y su resolución
-- ---------------------------------------------------------------------
CREATE TABLE REEMPLAZO (
    REEMPLAZO_ID               NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    EMPRESA_ID                 NUMBER(19) NOT NULL,
    SUCURSAL_ID                NUMBER(19) NOT NULL,
    ASIGNACION_TURNO_ID        NUMBER(19) NOT NULL,
    SOLICITANTE_ID             NUMBER(19) NOT NULL,
    REEMPLAZANTE_ID            NUMBER(19) NOT NULL,
    SUCURSAL_REEMPLAZANTE_ID   NUMBER(19) NOT NULL,
    MOTIVO                     VARCHAR2(200) NOT NULL,
    ESTADO                     VARCHAR2(10) DEFAULT 'SOLICITADO' NOT NULL,
    RESUELTO_POR               VARCHAR2(36),
    RESUELTO_EN                TIMESTAMP WITH TIME ZONE,
    COMENTARIO_RESOLUCION      VARCHAR2(300),
    CREADO_EN                  TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CREADO_POR                 VARCHAR2(36) NOT NULL,
    ACTUALIZADO_EN             TIMESTAMP WITH TIME ZONE,
    ACTUALIZADO_POR            VARCHAR2(36),
    CONSTRAINT PK_REEMPLAZO PRIMARY KEY (REEMPLAZO_ID),
    CONSTRAINT FK_REE_ASITUR_ASIGNA FOREIGN KEY (ASIGNACION_TURNO_ID) REFERENCES ASIGNACION_TURNO (ASIGNACION_TURNO_ID),
    CONSTRAINT CK_REEMPLAZO_1 CHECK (ESTADO IN ('SOLICITADO','APROBADO','RECHAZADO','CANCELADO')),
    CONSTRAINT CK_REEMPLAZO_2 CHECK (SOLICITANTE_ID <> REEMPLAZANTE_ID),
    CONSTRAINT CK_REEMPLAZO_3 CHECK (ESTADO IN ('SOLICITADO','CANCELADO') OR (RESUELTO_POR IS NOT NULL AND RESUELTO_EN IS NOT NULL)),
    CONSTRAINT CK_REEMPLAZO_4 CHECK (ESTADO <> 'RECHAZADO' OR COMENTARIO_RESOLUCION IS NOT NULL)
);
