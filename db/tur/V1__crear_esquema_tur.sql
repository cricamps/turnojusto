COMMENT ON COLUMN REEMPLAZO.ASIGNACION_TURNO_ID IS 'Turno que se quiere ceder';
COMMENT ON COLUMN REEMPLAZO.SOLICITANTE_ID IS 'Empleado que pide el reemplazo';
COMMENT ON COLUMN REEMPLAZO.REEMPLAZANTE_ID IS 'Empleado que cubrirá el turno';
COMMENT ON COLUMN REEMPLAZO.SUCURSAL_REEMPLAZANTE_ID IS 'Sucursal del reemplazante (apoyo entre sucursales)';
COMMENT ON COLUMN REEMPLAZO.MOTIVO IS 'Motivo de la solicitud';
COMMENT ON COLUMN REEMPLAZO.ESTADO IS 'Estado de la solicitud';
COMMENT ON COLUMN REEMPLAZO.RESUELTO_POR IS 'OID del coordinador que resolvió';
COMMENT ON COLUMN REEMPLAZO.RESUELTO_EN IS 'Momento de la resolución';
COMMENT ON COLUMN REEMPLAZO.COMENTARIO_RESOLUCION IS 'Obligatorio si se rechaza';
COMMENT ON COLUMN REEMPLAZO.CREADO_EN IS 'Fecha y hora de creación';
